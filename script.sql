-- TABLAS.

CREATE TABLE JUGADORES (
    ID_JUGADOR NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(100) NOT NULL,
    FECHA_REGISTRO DATE DEFAULT SYSDATE,

    CONSTRAINT PK_JUGADORES
        PRIMARY KEY (ID_JUGADOR)
);

COMMIT;

CREATE TABLE PARTIDAS (
    ID_PARTIDA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_JUGADOR NUMBER NOT NULL,
    PUNTUACION NUMBER DEFAULT 0,
    LONGITUD_SERPIENTE NUMBER DEFAULT 1,
    RESULTADO VARCHAR2(20),
    FECHA_PARTIDA DATE DEFAULT SYSDATE,

    CONSTRAINT PK_PARTIDAS
        PRIMARY KEY (ID_PARTIDA),

    CONSTRAINT FK_PARTIDAS_JUGADORES
        FOREIGN KEY (ID_JUGADOR)
        REFERENCES JUGADORES(ID_JUGADOR)
);

COMMIT;

// CONSULTA TABLAS.
SELECT * FROM JUGADORES;

SELECT * FROM PARTIDAS;

-- CONSULTA DE RANKING.
SELECT
    J.NOMBRE,
    P.PUNTUACION,
    P.LONGITUD_SERPIENTE,
    P.RESULTADO,
    P.FECHA_PARTIDA
FROM PARTIDAS P
INNER JOIN JUGADORES J
    ON J.ID_JUGADOR = P.ID_JUGADOR
ORDER BY P.PUNTUACION DESC; 